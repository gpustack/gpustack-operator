#!/usr/bin/env python3
"""Generate the golden contract fixtures shared by the Go and Python tests.

The fixtures are tiny: a safetensors file, its canonical manifest, and the
manifest digest sidecar. Both pkg/modeltransfer/protocol (Go) and
gpustack_model_transfer.core (Python) verify these exact bytes, so any drift between
the two implementations shows up as a failing digest check.

Run from the repository root with stdlib Python only:

    python3 model-transfer/contracts/generate_fixtures.py

The output is deterministic: tensor payload bytes come from a fixed counter,
never from entropy, so committed bytes and regenerated bytes are identical.
"""

import hashlib
import json
import struct
import sys
from pathlib import Path

FIXTURE_DIR = Path(__file__).resolve().parent / "fixtures" / "tiny_dense"

CONTRACT_VERSION = 2
ARTIFACT_UID = "model-fixture-tiny-dense"
SOURCE_GENERATION = 1

# name -> (dtype, shape); payload is deterministic counter bytes.
TENSORS = [
    ("lm_head.weight", "F32", [4, 3]),
    ("metadata.step", "I64", [1]),
    ("model.embed_tokens.weight", "F32", [4, 3]),
    ("model.layers.0.attn.q_proj.weight", "F32", [3, 3]),
    ("model.layers.0.attn.bias", "F32", [0]),
    ("model.layers.0.mlp.up_proj.weight", "F16", [2, 5]),
    ("model.norm.weight", "F32", [3]),
]

DTYPE_SIZE = {"F64": 8, "F32": 4, "F16": 2, "BF16": 2, "I64": 8, "I32": 4,
              "I16": 2, "I8": 1, "U8": 1, "BOOL": 1}


def payload_bytes(length: int, seed: int) -> bytes:
    return bytes((i * 7 + seed) % 256 for i in range(length))


def build_safetensors() -> tuple[bytes, dict]:
    header: dict[str, dict] = {}
    data = bytearray()
    for index, (name, dtype, shape) in enumerate(TENSORS):
        size = DTYPE_SIZE[dtype]
        count = 1
        for dim in shape:
            count *= dim
        begin = len(data)
        data += payload_bytes(count * size, seed=13 + index)
        header[name] = {
            "dtype": dtype,
            "shape": shape,
            "data_offsets": [begin, len(data)],
        }
    header_bytes = json.dumps(header, separators=(",", ":"), sort_keys=True).encode()
    blob = struct.pack("<Q", len(header_bytes)) + header_bytes + bytes(data)
    return blob, header


def main() -> int:
    blob, header = build_safetensors()
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    st_path = FIXTURE_DIR / "checkpoint.safetensors"
    st_path.write_bytes(blob)

    tensors = []
    base = 8 + int.from_bytes(blob[:8], "little")
    for index, (name, dtype, shape) in enumerate(TENSORS):
        entry = header[name]
        begin, end = entry["data_offsets"]
        absolute_begin = base + begin
        tensors.append({
            "name": name,
            "file": "checkpoint.safetensors",
            "dtype": dtype,
            "shape": shape,
            "data_begin": absolute_begin,
            "data_end": base + end,

        })

    manifest = {
        "contract_version": CONTRACT_VERSION,
        "artifact_uid": ARTIFACT_UID,
        "source_generation": SOURCE_GENERATION,
        "files": [{
            "path": "checkpoint.safetensors",
            "size": len(blob),

        }],
        "tensors": tensors,
    }
    manifest_bytes = json.dumps(manifest, sort_keys=True,
                                separators=(",", ":")).encode() + b"\n"
    (FIXTURE_DIR / "manifest.json").write_bytes(manifest_bytes)
    (FIXTURE_DIR / "manifest.sha256").write_text(
        hashlib.sha256(manifest_bytes).hexdigest() + "\n")
    print(f"wrote {FIXTURE_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
