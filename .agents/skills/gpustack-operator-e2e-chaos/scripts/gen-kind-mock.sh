#!/usr/bin/env bash
#
# gen-kind-mock.sh — generate (and optionally create) a parameterized multi-node Kind cluster
#                    configured for GPUStack Operator CPU-mock and Kueue TAS chaos testing.
#
# Usage:
#   gen-kind-mock.sh [--name <cluster>] [--workers <N>] [--zones <Z>] [--racks-per-zone <R>]
#                    [--region <region>] [--image <node-image>] [--kubeconfig <path>]
#                    [--out <file>] [--create]

set -euo pipefail

CLUSTER_NAME="gpustack-mock"
WORKERS=3
ZONES=2
RACKS_PER_ZONE=2
REGION="chaos-region"
NODE_IMAGE=""
KUBECONFIG_PATH=""
OUT_FILE=""
DO_CREATE=0

usage() {
  cat <<'EOF'
Usage: gen-kind-mock.sh [options]

Generate a kind.x-k8s.io/v1alpha4 Cluster configuration with 1 control-plane node and N worker
nodes carrying strictly nested topology.kubernetes.io/{region,zone,rack} labels via
kubeadmConfigPatches (nodeRegistration.kubeletExtraArgs.node-labels) and Kind node labels.

Options:
  --name <cluster>         Kind cluster name (default: gpustack-mock)
  --workers <N>            Number of worker nodes, e.g. 2..4 local or 8..32+ remote (default: 3)
  --zones <Z>              Number of availability zones across workers (default: 2)
  --racks-per-zone <R>     Number of racks per zone for strict TAS tree nesting (default: 2)
  --region <region>        Value for topology.kubernetes.io/region (default: chaos-region)
  --image <image>          Optional kindest/node:<tag> image for all nodes
  --kubeconfig <path>      Optional kubeconfig destination when --create is passed
  --out <file>             Write rendered YAML to <file> instead of stdout
  --create                 Invoke `kind create cluster` with the generated config
  -h, --help               Show this help message
EOF
}

is_pos_int() {
  [[ "${1:-}" =~ ^[1-9][0-9]*$ ]]
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --name requires a value" >&2; exit 2; }
      CLUSTER_NAME="$2"
      shift 2
      ;;
    --name=*)
      CLUSTER_NAME="${1#--name=}"
      shift
      ;;
    --workers)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --workers requires a positive integer" >&2; exit 2; }
      WORKERS="$2"
      shift 2
      ;;
    --workers=*)
      WORKERS="${1#--workers=}"
      shift
      ;;
    --zones)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --zones requires a positive integer" >&2; exit 2; }
      ZONES="$2"
      shift 2
      ;;
    --zones=*)
      ZONES="${1#--zones=}"
      shift
      ;;
    --racks-per-zone)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --racks-per-zone requires a positive integer" >&2; exit 2; }
      RACKS_PER_ZONE="$2"
      shift 2
      ;;
    --racks-per-zone=*)
      RACKS_PER_ZONE="${1#--racks-per-zone=}"
      shift
      ;;
    --region)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --region requires a value" >&2; exit 2; }
      REGION="$2"
      shift 2
      ;;
    --region=*)
      REGION="${1#--region=}"
      shift
      ;;
    --image)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --image requires a value" >&2; exit 2; }
      NODE_IMAGE="$2"
      shift 2
      ;;
    --image=*)
      NODE_IMAGE="${1#--image=}"
      shift
      ;;
    --kubeconfig)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --kubeconfig requires a path" >&2; exit 2; }
      KUBECONFIG_PATH="$2"
      shift 2
      ;;
    --kubeconfig=*)
      KUBECONFIG_PATH="${1#--kubeconfig=}"
      shift
      ;;
    --out)
      [[ $# -ge 2 ]] || { echo "gen-kind-mock: --out requires a file path" >&2; exit 2; }
      OUT_FILE="$2"
      shift 2
      ;;
    --out=*)
      OUT_FILE="${1#--out=}"
      shift
      ;;
    --create)
      DO_CREATE=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "gen-kind-mock: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

[[ -n "$CLUSTER_NAME" ]] || { echo "gen-kind-mock: --name must not be empty" >&2; exit 2; }
[[ -n "$REGION" ]] || { echo "gen-kind-mock: --region must not be empty" >&2; exit 2; }
is_pos_int "$WORKERS" || { echo "gen-kind-mock: --workers must be >= 1 (got '${WORKERS}')" >&2; exit 2; }
is_pos_int "$ZONES" || { echo "gen-kind-mock: --zones must be >= 1 (got '${ZONES}')" >&2; exit 2; }
is_pos_int "$RACKS_PER_ZONE" || { echo "gen-kind-mock: --racks-per-zone must be >= 1 (got '${RACKS_PER_ZONE}')" >&2; exit 2; }

render_cluster_yaml() {
  printf '# Generated by gen-kind-mock.sh: cluster=%s workers=%s zones=%s racksPerZone=%s\n' \
    "$CLUSTER_NAME" "$WORKERS" "$ZONES" "$RACKS_PER_ZONE"
  printf 'kind: Cluster\n'
  printf 'apiVersion: kind.x-k8s.io/v1alpha4\n'
  printf 'nodes:\n'
  printf '  - role: control-plane\n'
  if [[ -n "$NODE_IMAGE" ]]; then
    printf '    image: "%s"\n' "$NODE_IMAGE"
  fi
  cat <<'EOF'
    kubeadmConfigPatches:
      - |
        kind: ClusterConfiguration
        apiServer:
          extraArgs:
            enable-aggregator-routing: "true"
EOF

  local i zone_num local_rack rack_num zone_val rack_val node_labels_csv
  for ((i = 1; i <= WORKERS; i++)); do
    zone_num=$(( ((i - 1) % ZONES) + 1 ))
    local_rack=$(( (((i - 1) / ZONES) % RACKS_PER_ZONE) + 1 ))
    # Every rack belongs to a single zone so Kueue TAS sees a strictly nested region -> zone -> rack tree.
    rack_num=$(( ((zone_num - 1) * RACKS_PER_ZONE) + local_rack ))
    zone_val="zone-${zone_num}"
    rack_val="rack-${rack_num}"
    node_labels_csv="topology.kubernetes.io/region=${REGION},topology.kubernetes.io/zone=${zone_val},topology.kubernetes.io/rack=${rack_val}"

    printf '  - role: worker\n'
    if [[ -n "$NODE_IMAGE" ]]; then
      printf '    image: "%s"\n' "$NODE_IMAGE"
    fi
    printf '    labels:\n'
    printf '      topology.kubernetes.io/region: "%s"\n' "$REGION"
    printf '      topology.kubernetes.io/zone: "%s"\n' "$zone_val"
    printf '      topology.kubernetes.io/rack: "%s"\n' "$rack_val"
    cat <<EOF
    kubeadmConfigPatches:
      - |
        kind: JoinConfiguration
        nodeRegistration:
          kubeletExtraArgs:
            node-labels: "${node_labels_csv}"
EOF
  done
}

TMP_CFG=""
cleanup_tmp() {
  if [[ -n "$TMP_CFG" && -f "$TMP_CFG" ]]; then
    rm -f "$TMP_CFG"
  fi
}
trap cleanup_tmp EXIT

if [[ -n "$OUT_FILE" ]]; then
  mkdir -p "$(dirname "$OUT_FILE")"
  render_cluster_yaml >"$OUT_FILE"
  CFG_PATH="$OUT_FILE"
elif [[ "$DO_CREATE" -eq 1 ]]; then
  TMP_CFG="$(mktemp)"
  render_cluster_yaml >"$TMP_CFG"
  CFG_PATH="$TMP_CFG"
else
  render_cluster_yaml
  exit 0
fi

if [[ "$DO_CREATE" -eq 1 ]]; then
  command -v kind >/dev/null 2>&1 || {
    echo "gen-kind-mock: 'kind' binary not found in PATH" >&2
    exit 1
  }
  create_args=(create cluster --name "$CLUSTER_NAME" --config "$CFG_PATH" --wait 120s)
  if [[ -n "$KUBECONFIG_PATH" ]]; then
    mkdir -p "$(dirname "$KUBECONFIG_PATH")"
    create_args+=(--kubeconfig "$KUBECONFIG_PATH")
  fi
  if [[ -n "$NODE_IMAGE" ]]; then
    create_args+=(--image "$NODE_IMAGE")
  fi
  kind "${create_args[@]}"
fi
