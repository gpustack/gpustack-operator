// baselineDir is the directory holding the captured application values, relative to this
// package. The captured files are the parity oracle for translating these Go values
// templates into chart values, so they outlive this test.
const baselineDir = "../../../testing/chart-baseline"

// baselineHeader prefixes every captured file. It carries no version and no timestamp, so
// re-capturing an unchanged template rewrites the file byte for byte.
const baselineHeader = `# Generated by TestDumpChartValuesBaseline in pkg/worker/kuberess. DO NOT EDIT.
# Regenerate: go test ./pkg/worker/kuberess/ -run TestDumpChartValuesBaseline -args -update
`

// updateBaseline rewrites the captured files instead of verifying them.
var updateBaseline = flag.Bool("update", false, "rewrite the chart values baseline under testing/chart-baseline")

// TestDumpChartValuesBaseline captures the values each application installer hands to Helm
// today, one file per application. Without -update it verifies the committed capture
// instead of rewriting it, which is what pins the output as byte-stable across runs.
//
// The rendering inputs are pinned to the stock defaults rather than read from the cluster
// or the host environment: a capture that varies per machine is worthless as an oracle.
func TestDumpChartValuesBaseline(t *testing.T) {
	// The node-feature-discovery template reads this variable while rendering. It is the
	// only environment lookup left in the rendering path, so pin it to its default.
	t.Setenv("GPUSTACK_PCI_CLASS_PREFIXES", "")

	// Each case names the application, the chart its installer renders values for — the two
	// differ for the device-managers, which come from the operator's own chart — and how to
	// render them. The chart name is taken from the case rather than repeated at the call
	// site, so a case is the single place an application is spelled out.
	testCases := []struct {
		name   string
		chart  string
		values func(chart string) helm.ChartValues
	}{
		{
			name:  "kueue",
			chart: "kueue",
			values: func(chart string) helm.ChartValues {
				return getKueueChartTemplateValues(chart, kueueBaselineContext(), extendKueueChartValuesTemplateFuncMap())
			},
		},
		{
			name:  "node-feature-discovery",
			chart: "node-feature-discovery",
			values: func(chart string) helm.ChartValues {
				return getNfdChartTemplateValues(chart, nodeFeatureDiscoveryBaselineContext(), extendNfdChartValuesTemplateFuncMap())
			},
		},
		{
			name:  "csi-driver-nfs",
			chart: "csi-driver-nfs",
			values: func(chart string) helm.ChartValues {
				return getCSIDriverNFSChartTemplateValues(chart, csiDriverNFSBaselineContext())
			},
		},
		{
			name:  "csi-driver-s3",
			chart: "csi-driver-s3",
			values: func(chart string) helm.ChartValues {
				return getCSIDriverS3ChartTemplateValues(chart, csiDriverS3BaselineContext())
			},
		},
		{
			name:  "device-manager",
			chart: "gpustack-operator",
			values: func(chart string) helm.ChartValues {
				return getGPUStackDeviceManagerChartTemplateValues(chart, deviceManagerBaselineContext())
			},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			got := renderBaseline(t, tc.values(tc.chart))
			path := filepath.Join(baselineDir, tc.name+".yaml")

			if *updateBaseline {
				require.NoError(t, os.MkdirAll(baselineDir, 0o755), "create baseline directory")
				require.NoError(t, os.WriteFile(path, got, 0o644), "write baseline")
				return
			}

			want, err := os.ReadFile(path)
			require.NoError(t, err, "read baseline, capture it with -args -update")
			assert.Equal(t, string(want), string(got), "baseline is stale, recapture it with -args -update")
		})
	}
}

// renderBaseline renders the given values twice and returns the file content to capture.
// Rendering twice catches nondeterminism inside the template itself, so a template that
// ranges a map in iteration order fails here instead of producing a flapping oracle.
func renderBaseline(t *testing.T, values helm.ChartValues) []byte {
	t.Helper()

	first := marshalBaselineValues(t, values)
	require.Equal(t, string(first), string(marshalBaselineValues(t, values)), "rendering is not deterministic")

	return append([]byte(baselineHeader), first...)
}

// marshalBaselineValues renders the values and encodes them canonically. sigs.k8s.io/yaml
// sorts keys through its JSON round trip and is the encoder Helm itself uses, so the
// capture is both stable and directly comparable with chart values.
func marshalBaselineValues(t *testing.T, values helm.ChartValues) []byte {
	t.Helper()

	v, err := values.GetValues(t.Context())
	require.NoError(t, err, "render chart values")

	b, err := yaml.Marshal(v)
	require.NoError(t, err, "marshal chart values")

	return b
}

// baselineValuesContext returns the shared context InstallApplications builds, pinned to
// the stock setting defaults: an unconfigured install is what the chart values have to
// reproduce.
func baselineValuesContext() map[string]any {
	return map[string]any{
		// ContainerRegistry and ContainerNamespace default to blank, so every template
		// applies its own "docker.io" and "gpustack" fallback.
		"ContainerRegistry":  "",
		"ContainerNamespace": "",
		// ImagePullSecrets defaults to blank, which InstallApplications maps to no secrets.
		"ImagePullSecrets": []string(nil),
		"ImagePullPolicy":  "IfNotPresent",
		// The known manufacturers are returned sorted and match the operator chart's own
		// "manufacturers" default, which is the set the chart has to cover.
		"Manufacturers": nodefeature.GetKnownAcceleratableManufacturers(),
		// ExecuteInstall adds this label to every installer's context.
		"ManagedLabel": "gpustack.ai/managed",
		// Each installer takes the namespace from the Helm client, which defaults to the
		// system namespace. It is spelled out instead of taken from SystemNamespaceName,
		// which resolves KUBERNETES_POD_NAMESPACE at package initialization and would leak
		// the developer's environment into the capture.
		"Namespace": "gpustack-system",
		// "Env" is deliberately absent: ExecuteInstall fills it from the host's proxy
		// variables and no values template reads it.
	}
}

func kueueBaselineContext() map[string]any {
	c := baselineValuesContext()
	c["Release"] = kueueReleaseName
	// installKueue pins the controller image to the Kueue version it bundles. The
	// Kubernetes-version branch there selects the chart tarball, not this tag, so both
	// branches render identical values and one capture covers them.
	c["Tag"] = "v0.18.2"
	return c
}

func nodeFeatureDiscoveryBaselineContext() map[string]any {
	c := baselineValuesContext()
	c["Release"] = "gpustack-node-feature-discovery"
	return c
}

func csiDriverNFSBaselineContext() map[string]any {
	c := baselineValuesContext()
	c["Release"] = "gpustack-csi-driver-nfs"
	c["DriverName"] = CSIProvisionerNFS
	return c
}

func csiDriverS3BaselineContext() map[string]any {
	c := baselineValuesContext()
	c["Release"] = "gpustack-csi-driver-s3"
	c["DriverName"] = CSIProvisionerS3
	return c
}

// deviceManagerBaselineContext leaves the running worker's image undetected, the branch
// extractWorkerImage takes outside the cluster. That branch renders the superset of keys:
// the chart composes its image from the global registry and namespace instead of pinning
// the worker's own reference.
func deviceManagerBaselineContext() map[string]any {
	c := baselineValuesContext()
	c["Release"] = "gpustack-operator-device-manager"
	c["ImageRepository"] = ""
	c["ImageTag"] = ""

	manufacturers := nodefeature.GetKnownAcceleratableManufacturers()
	vendorIDs := make(map[string]string, len(manufacturers))
	for _, m := range manufacturers {
		vendorIDs[m] = nodefeature.GetPciVendorID(m)
	}
	c["ManufacturerVendorIDs"] = vendorIDs

	return c
}
